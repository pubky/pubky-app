'use client';

import { hasAccountState } from '@/stores/auth/auth.selectors';
import { useAuthStore } from '@/stores/auth/auth.store';
import { hasSignupAttemptForSecretState } from '@/stores/onboarding/onboarding.selectors';
import { useOnboardingStore } from '@/stores/onboarding/onboarding.store';

/**
 * Whether the stored secret key may protect an account, so the backup surfaces (`AlertBackup` and the `/logout`
 * backup prompt) must keep asking for a backup. Not an action guard.
 *
 * True while the auth store holds an account (`hasAccountState`: a session, a reference to restore, or a restore
 * that is running or failed), or while a sign-up for the stored secret is recorded (`hasSignupAttemptForSecretState`):
 * `AuthController.signUp` records the attempt before it signs the created account in, so after a failed sign-in the
 * homeserver account exists although the auth store holds no session. False for a visitor whose only identity is the
 * pubky generated by the onboarding key step, who has nothing to lose yet (#2955).
 */
export function useHasBackupAccount(): boolean {
  const hasAuthAccount = useAuthStore(hasAccountState);
  const hasSignupAttempt = useOnboardingStore(hasSignupAttemptForSecretState);
  return hasAuthAccount || hasSignupAttempt;
}
